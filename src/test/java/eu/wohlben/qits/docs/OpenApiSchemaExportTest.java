package eu.wohlben.qits.docs;

import static io.restassured.RestAssured.given;

import eu.wohlben.qits.docs.contracts.ContractProfile;
import io.quarkus.test.junit.QuarkusTest;
import io.quarkus.test.junit.TestProfile;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import org.junit.jupiter.api.Test;

/**
 * Writes {@code docs/openapi.yml} as a side effect of the suite, the same way the sibling services
 * do (qits-1925). Checking the document in is what turns an API change into a reviewable diff
 * instead of something a caller discovers at runtime.
 *
 * <p>This is a test only because {@code @QuarkusTest} is the cheapest way to stand the application
 * up and read its own {@code /docs/q/openapi} — that path is {@code
 * quarkus.http.non-application-root-path}, so it moves with that key alone. The status check is the
 * one assertion: the document is served at that path. Everything else is the diff.
 *
 * <p>The document has one source. Every route here is a raw Vert.x route that no annotation
 * describes, so what SmallRye serves is {@code src/main/resources/META-INF/openapi.yaml}, with the
 * title and version Quarkus adds. It runs under {@link ContractProfile}, the profile the contract
 * tests share, so the suite boots the application once for all of them.
 */
@QuarkusTest
@TestProfile(ContractProfile.class)
public class OpenApiSchemaExportTest {

  @Test
  public void exportOpenApiSchema() throws Exception {
    String schema =
        given().when().get("/docs/q/openapi").then().statusCode(200).extract().asString();

    // A single-module project: the working directory is the repository root.
    Path docsDir = Paths.get("docs");
    if (!Files.exists(docsDir)) {
      Files.createDirectories(docsDir);
    }

    String header =
        "# THIS FILE IS GENERATED BY OpenApiSchemaExportTest — DO NOT EDIT MANUALLY.\n"
            + "# Run `./mvnw test -Dtest=OpenApiSchemaExportTest"
            + " -Dsurefire.failIfNoSpecifiedTests=false` to regenerate.\n";

    Files.writeString(docsDir.resolve("openapi.yml"), header + schema);
  }
}
